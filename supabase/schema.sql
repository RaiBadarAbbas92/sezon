-- Sezon storefront — Supabase schema (Supabase Dashboard → SQL Editor → run this, then supabase/seed.sql).
-- Same tables/columns as the Bustaniya store backend, so its admin panel can manage products, categories and orders.
-- Every statement is "if not exists", so it is safe to run on a project that already has the Bustaniya scripts.

create extension if not exists pgcrypto;

-- PRODUCTS — img/size/color are JSON-string arrays; extra fields (slug, status, materials, care, rating) in cost_breakdown.metadata
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  description text default '',
  price numeric(12,2) not null default 0,
  compare_at_price numeric(12,2),
  article_number text unique,
  category text default '',            -- most specific slug, e.g. 'cardigans' or 'bags' ("Clothing > Cardigans" also matches)
  size text default '[]',
  color text default '[]',             -- '["Rose|#E9B7B4", "Ivory"]'
  img text default '[]',
  instock boolean not null default true,
  new boolean not null default false,
  bestsellere boolean not null default false,
  delivery_fee_mode text default 'inherit',
  delivery_fee_pkr numeric(12,2),
  delivery_info text,
  instagram_video_url text,
  cost_total_pkr numeric(12,2) not null default 0,
  cost_breakdown jsonb not null default '{}'::jsonb
);

create table if not exists public.inventory (
  id bigint generated by default as identity primary key,
  product_id bigint not null unique references public.products(id) on delete cascade,
  stock_quantity integer not null default 0,
  low_stock_threshold integer not null default 5,
  sku text default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete cascade,
  quantity_change integer not null default 0,
  reason text,
  stock_before integer,
  stock_after integer,
  created_at timestamptz not null default now()
);

-- CATEGORIES — the storefront's structure is fixed in lib/brand.ts; rows here feed the admin dropdown + cover images.
-- icon: rabbit | bag | flower | sparkles | gift | shirt
create table if not exists public.catalog_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  icon text,
  image_url text,
  sort_order integer not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.catalog_categories add column if not exists parent_slug text; -- null = top-level section
alter table public.catalog_categories add column if not exists icon text;
alter table public.catalog_categories add column if not exists image_url text;
alter table public.catalog_categories add column if not exists sort_order integer not null default 100;
alter table public.catalog_categories add column if not exists is_active boolean not null default true;

-- ORDERS (written by /api/orders with the service role key)
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  order_number text unique,
  checkout_token uuid,
  status text default 'pending',
  courier text,
  courier_status text default 'pending',
  courier_tracking_number text,
  tracking_number text,
  courier_response jsonb,
  postex_response jsonb,
  payment_method text,
  subtotal numeric(12,2), subtotal_pkr numeric(12,2),
  shipping_fee_pkr numeric(12,2), delivery_pkr numeric(12,2),
  total numeric(12,2), total_pkr numeric(12,2),
  shipping_full_name text, shipping_phone text,
  shipping_line1 text, shipping_line2 text, shipping_address text,
  shipping_city text, shipping_region text, shipping_country text default 'Pakistan',
  shipping_postal_code text,
  guest_name text, guest_phone text, guest_email text, customer_email text,
  items jsonb not null default '[]'::jsonb,
  tags text[] default '{}',
  notes text, internal_notes text
);
create index if not exists orders_created_at_idx on public.orders (created_at desc);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  title text,
  price_pkr numeric(12,2), unit_price_pkr numeric(12,2),
  quantity integer not null default 1,
  line_total_pkr numeric(12,2),
  size text, color text, image_url text,
  created_at timestamptz not null default now()
);
create index if not exists order_items_order_idx on public.order_items (order_id);

-- SECURITY — the public (anon) key may only read the catalogue; orders are server-only (service role bypasses RLS).
alter table public.products enable row level security;
alter table public.inventory enable row level security;
alter table public.catalog_categories enable row level security;
alter table public.inventory_movements enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "public read products" on public.products;
create policy "public read products" on public.products for select to anon, authenticated using (true);
drop policy if exists "public read inventory" on public.inventory;
create policy "public read inventory" on public.inventory for select to anon, authenticated using (true);
drop policy if exists "public read categories" on public.catalog_categories;
create policy "public read categories" on public.catalog_categories for select to anon, authenticated using (is_active);

revoke all on public.orders, public.order_items, public.inventory_movements from anon, authenticated;
